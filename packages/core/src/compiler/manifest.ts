import type { ActionGuardManifest, GeneratedArtifacts, McpToolDefinition } from '../types.js';
import { ActionGuardManifestSchema } from '../types.js';

/**
 * Validates and compiles an actionguard.json into official MCP Registry, A2A, and DNS-AID formats.
 */
export function validateManifest(rawJson: unknown): ActionGuardManifest {
  return ActionGuardManifestSchema.parse(rawJson);
}

/**
 * Compiles to official MCP Registry server.json (2025-12-11 schema).
 */
export function compileToMcpRegistry(manifest: ActionGuardManifest): string {
  const mcpEndpoint = manifest.endpoints.find((e) => e.protocol === 'mcp');

  const serverJson: Record<string, unknown> = {
    $schema: 'https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json',
    name: manifest.name.includes('/') ? manifest.name : `io.actionguard/${manifest.name}`,
    title: manifest.title,
    description: manifest.description,
    version: manifest.version,
  };

  if (manifest.repository) {
    serverJson.repository = {
      url: manifest.repository.url,
      source: manifest.repository.source || 'github',
    };
  }

  if (mcpEndpoint) {
    serverJson.remotes = [
      {
        type: mcpEndpoint.transport || 'streamable-http',
        url: mcpEndpoint.url,
      },
    ];
  }

  return JSON.stringify(serverJson, null, 2);
}

/**
 * Compiles to A2A Protocol v1.0 Agent Card (/.well-known/agent-card.json).
 */
export function compileToA2AAgentCard(manifest: ActionGuardManifest): string {
  const a2aEndpoint = manifest.endpoints.find((e) => e.protocol === 'a2a') || manifest.endpoints[0];

  const agentCard = {
    name: manifest.title,
    description: manifest.description,
    version: manifest.version,
    documentationUrl: manifest.repository?.url || `https://${manifest.domain}/docs`,
    provider: {
      organization: manifest.provider?.organization || manifest.title,
      url: manifest.provider?.url || `https://${manifest.domain}`,
    },
    supportedInterfaces: [
      {
        url: a2aEndpoint.url,
        protocolBinding: a2aEndpoint.binding || 'JSONRPC',
        protocolVersion: '1.0',
      },
    ],
    capabilities: {
      streaming: true,
      pushNotifications: false,
      extendedAgentCard: false,
    },
    defaultInputModes: ['application/json'],
    defaultOutputModes: ['application/json'],
    skills: manifest.capabilities.tools.map((t) => ({
      id: t.id,
      name: t.name || t.id,
      description: t.description,
      tags: t.compliance || ['general'],
      examples: t.examples || [`Use ${t.name || t.id} to process request`],
    })),
  };

  return JSON.stringify(agentCard, null, 2);
}

/**
 * Compiles to DNS-AID RFC 8552 zone records (SVCB & TXT).
 */
export function compileToDnsAidRecords(manifest: ActionGuardManifest): string {
  const prefix = manifest.dnsAid?.agentPrefix || 'agent';
  const zone = manifest.dnsAid?.zone || manifest.domain;
  const mcpEndpoint = manifest.endpoints.find((e) => e.protocol === 'mcp');
  const a2aEndpoint = manifest.endpoints.find((e) => e.protocol === 'a2a');

  let records = `; DNS-AID (RFC 8552 / RFC 9460) Records for ${zone}\n`;
  records += `; Generated by ActionGuard.ai on ${new Date().toISOString()}\n\n`;

  if (mcpEndpoint) {
    const urlObj = new URL(mcpEndpoint.url);
    const path = urlObj.pathname + (urlObj.search || '');
    records += `_${prefix}._mcp._agents.${zone}.   IN  SVCB  1 ${urlObj.hostname}. (\n`;
    records += `                                    alpn="h2"\n`;
    records += `                                    port=${urlObj.port || (urlObj.protocol === 'https:' ? '443' : '80')}\n`;
    records += `                                    key65300="path=${path}"\n`;
    records += '                                )\n';
  }

  if (a2aEndpoint) {
    const urlObj = new URL(a2aEndpoint.url);
    const path = urlObj.pathname + (urlObj.search || '');
    records += `_${prefix}._a2a._agents.${zone}.   IN  SVCB  1 ${urlObj.hostname}. (\n`;
    records += `                                    alpn="h2"\n`;
    records += `                                    port=${urlObj.port || (urlObj.protocol === 'https:' ? '443' : '80')}\n`;
    records += `                                    key65300="path=${path}"\n`;
    records += '                                )\n';
  }

  records += `_${prefix}._meta._agents.${zone}.  IN  TXT   "v=aid1;ver=${manifest.version};name=${manifest.name}"\n`;
  return records;
}

/**
 * Compiles a turnkey GitHub Action CI/CD workflow to test and block schema drift on PRs.
 */
export function compileToGitHubAction(manifest: ActionGuardManifest): string {
  return `name: ActionGuard Protocol CI

on:
  pull_request:
    branches: [main]
  push:
    branches: [main]

jobs:
  verify:
    name: Verify MCP & A2A Schemas
    runs-on: ubuntu-latest
    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: 20

      - name: Run ActionGuard Schema Gate
        run: |
          npx --yes @actionguard/cli check --manifest actionguard.json
`;
}

/**
 * Synthesizes a starter actionguard.json from inspected tools and domain.
 */
export function generateStarterManifest(
  domain: string,
  targetUrl: string,
  tools: McpToolDefinition[],
): ActionGuardManifest {
  const cleanDomain = domain.replace(/^https?:\/\//, '').split('/')[0];
  const name = `com.${cleanDomain.replace(/\./g, '_')}/agent`;

  return {
    $schema: 'https://actionguard.ai/schemas/v1/manifest.schema.json',
    name,
    title: `${cleanDomain} Agent`,
    description: `Discovered and verified agent service running at ${targetUrl}`,
    version: '1.0.0',
    domain: cleanDomain,
    endpoints: [
      {
        protocol: 'mcp',
        transport: 'streamable-http',
        url: targetUrl,
        auth: { type: 'none' },
      },
    ],
    capabilities: {
      tools: tools.map((t) => ({
        id: t.name,
        name: t.name,
        description: t.description || '',
        annotations: t.annotations || { readOnlyHint: true },
        inputSchema: t.inputSchema || { type: 'object' },
        examples: [`Run ${t.name}`],
      })),
    },
    dnsAid: {
      enabled: true,
      agentPrefix: 'agent',
      zone: cleanDomain,
    },
  };
}

/**
 * Generates all 5 standard artifacts for an inspection report.
 */
export function generateArtifacts(manifest: ActionGuardManifest): GeneratedArtifacts {
  return {
    actionguardJson: JSON.stringify(manifest, null, 2),
    mcpServerJson: compileToMcpRegistry(manifest),
    a2aAgentCardJson: compileToA2AAgentCard(manifest),
    dnsAidRecords: compileToDnsAidRecords(manifest),
    githubActionWorkflow: compileToGitHubAction(manifest),
  };
}
